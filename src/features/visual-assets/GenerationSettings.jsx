import { ChevronDownIcon, InfoIcon, SettingsIcon } from '../../components/icons.jsx'
import { ASPECT_RATIOS, IMAGE_QUALITIES, VISUAL_STYLES } from './options.js'

function SelectField({ id, label, value, options, onChange }) {
  return (
    <div className="field">
      <label htmlFor={id} className="field__label">{label}</label>
      <div className="select">
        <select id={id} value={value} onChange={(event) => onChange(event.target.value)}>
          {options.map((option) => (
            <option key={option.value} value={option.value}>
              {option.label}
            </option>
          ))}
        </select>
        <ChevronDownIcon />
      </div>
    </div>
  )
}

function GenerationSettings({ settings, onChange }) {
  const update = (key) => (value) => onChange({ ...settings, [key]: value })

  return (
    <section className="panel vag-settings" aria-labelledby="settings-heading">
      <h2 id="settings-heading" className="vag-settings__title">
        <SettingsIcon />
        Generation settings
      </h2>

      <div className="vag-settings__grid">
        <SelectField
          id="visual-style"
          label="Visual style"
          value={settings.style}
          options={VISUAL_STYLES}
          onChange={update('style')}
        />
        <SelectField
          id="aspect-ratio"
          label="Aspect ratio"
          value={settings.aspectRatio}
          options={ASPECT_RATIOS}
          onChange={update('aspectRatio')}
        />
        <SelectField
          id="image-quality"
          label="Image quality"
          value={settings.quality}
          options={IMAGE_QUALITIES}
          onChange={update('quality')}
        />
        <p className="vag-settings__info">
          <InfoIcon />
          Images will be generated by AI from the scene prompts. You can review and
          regenerate any image later.
        </p>
      </div>
    </section>
  )
}

export default GenerationSettings
